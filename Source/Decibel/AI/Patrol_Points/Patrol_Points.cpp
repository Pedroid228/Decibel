APatrol_Points::APatrol_Points()
{
}
//------------------------------------------------------------------------------------------------------------
int32 APatrol_Points::Num()
{
	return Points.Num();
}
//------------------------------------------------------------------------------------------------------------
FVector APatrol_Points::Get_Point_By_Index(int32 index)
{
	FVector point_pos;

	if (Points.IsValidIndex(index))
		point_pos = Points[index];

	return point_pos;
}
